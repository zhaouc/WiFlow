"""Store campus login secrets in Secret Service, never in JSON or command lines."""
from __future__ import annotations

import os
import hashlib
from pathlib import Path
import shutil
import subprocess
import tempfile


def secret_service_available() -> bool:
    return shutil.which('secret-tool') is not None


def get_secret(kind: str) -> str:
    if not secret_service_available():
        return ''
    # Old keyring records remain readable after upgrading; new writes always
    # use WiFlow. Do not copy secrets to plaintext settings or stdout.
    for application in ('wiflow', 'wifi-assistant'):
        try:
            p = subprocess.run(['secret-tool', 'lookup', 'application', application, 'kind', kind],
                               stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                               text=True, timeout=8, check=False)
            if p.returncode == 0:
                return p.stdout.rstrip('\n')
        except (OSError, subprocess.TimeoutExpired):
            continue
    return ''


def put_secret(kind: str, password: str) -> bool:
    """Store only in Secret Service; drop old application keys on update/delete."""
    if not secret_service_available():
        return False
    try:
        if password:
            p = subprocess.run(['secret-tool', 'store', '--label=WiFlow credential',
                                'application', 'wiflow', 'kind', kind],
                               input=password, text=True, stdout=subprocess.DEVNULL,
                               stderr=subprocess.DEVNULL, timeout=12, check=False)
            if p.returncode:
                return False
        else:
            p = subprocess.run(['secret-tool', 'clear', 'application', 'wiflow', 'kind', kind],
                               stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                               timeout=8, check=False)
            if p.returncode:
                return False
        # Never let a stale old key reappear after WiFlow updates/clears it.
        subprocess.run(['secret-tool', 'clear', 'application', 'wifi-assistant', 'kind', kind],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                       timeout=8, check=False)
        return True
    except (OSError, subprocess.TimeoutExpired):
        return False


def split_nmcli_record(line: str) -> list[str]:
    """Decode NetworkManager's escaped colons and backslashes in terse output."""
    result, buf, escaped = [], [], False
    for character in line:
        if escaped:
            buf.append(character)
            escaped = False
        elif character == "\\":
            escaped = True
        elif character == ":":
            result.append("".join(buf))
            buf = []
        else:
            buf.append(character)
    if escaped:
        buf.append("\\")
    result.append("".join(buf))
    return result


def _legacy_profile_matches(name: str, ssid: str) -> bool:
    """Only match exact profiles generated by the old Ubuntu release."""
    return name == 'WIFI助手-' + hashlib.sha256(ssid.encode('utf-8')).hexdigest()[:16]


def cleanup_legacy_wifi_profiles(runner) -> tuple[int, int]:
    """Immediately remove old app-owned NetworkManager profiles, even active.

    This can temporarily disconnect Wi-Fi. No user-created profiles or
    profiles with arbitrary names are deleted. UUIDs avoid name collisions.
    """
    removed = skipped = 0
    entries = runner('-t', '-f', 'NAME,UUID,TYPE', 'connection', 'show')
    for line in entries.splitlines():
        parts = split_nmcli_record(line)
        if len(parts) < 3 or parts[2] not in ('wifi', '802-11-wireless'):
            continue
        name, uuid = parts[:2]
        if not uuid or not name.startswith('WIFI助手-'):
            continue
        try:
            ssid = split_nmcli_record(runner('-g', '802-11-wireless.ssid',
                                              'connection', 'show', 'uuid', uuid).strip())[0]
            if _legacy_profile_matches(name, ssid):
                runner('connection', 'delete', 'uuid', uuid)
                removed += 1
            else:
                skipped += 1
        except (RuntimeError, ValueError, OSError, IndexError):
            skipped += 1
    return removed, skipped


def find_wifi_profile(ssid: str, runner) -> tuple[str, str] | None:
    """Return the saved NetworkManager Wi-Fi profile for its actual SSID."""
    entries = runner('-t', '-f', 'NAME,UUID,TYPE', 'connection', 'show')
    for line in entries.splitlines():
        parts = split_nmcli_record(line)
        if len(parts) < 3 or parts[2] not in ('wifi', '802-11-wireless'):
            continue
        name, uuid = parts[:2]
        if name.startswith('WIFI助手-'):
            continue  # Never reuse legacy app-generated profiles.
        if uuid:
            configured_ssid = split_nmcli_record(runner('-g', '802-11-wireless.ssid',
                                  'connection', 'show', 'uuid', uuid).strip())[0]
            if configured_ssid == ssid:
                return 'uuid', uuid
        elif name == ssid:
            return 'id', name
    return None


def connect_wifi(ssid: str, password: str, runner) -> None:
    """Use native saved Wi-Fi profiles; new profiles are named the real SSID."""
    if not ssid:
        raise ValueError('尚未设置 Wi-Fi 名称')
    if '\n' in password or '\r' in password:
        raise ValueError('Wi-Fi 密码不能包含换行符')
    existing = find_wifi_profile(ssid, runner)
    if existing is not None:
        # System-saved credentials remain authoritative. Profiles using
        # agent-owned or unsaved PSKs need the app's secret on each activation.
        activation_password = ''
        if password:
            key_mgmt = runner('-g', '802-11-wireless-security.key-mgmt',
                              'connection', 'show', *existing).strip()
            if key_mgmt in ('wpa-psk', 'sae'):
                flags = runner('-g', '802-11-wireless-security.psk-flags',
                               'connection', 'show', *existing).strip()
                if flags and int(flags.split()[0]) & 3:
                    activation_password = password
        activate_wifi(existing, activation_password, runner)
        return

    available = runner('-t', '-f', 'SSID,SECURITY', 'device', 'wifi', 'list', '--rescan', 'no')
    security = ''
    for line in available.splitlines():
        fields = split_nmcli_record(line)
        if len(fields) >= 2 and fields[0] == ssid:
            security = fields[1].upper()
            break
    if '802.1X' in security or 'EAP' in security:
        raise ValueError('该 Wi-Fi 使用企业级身份认证，请在 Ubuntu 系统网络设置中配置 802.1X')
    if not password:
        if security not in ('', '--', 'NONE'):
            raise ValueError('该 Wi-Fi 需要密码；请先输入 Wi-Fi 密码')
        runner('device', 'wifi', 'connect', ssid)
        return

    key_mgmt = 'sae' if 'WPA3' in security and 'WPA2' not in security else 'wpa-psk'
    # Persistent NetworkManager profile; original SSID is also its display name.
    # Only created for unsaved Wi-Fi, never overwrites an existing profile.
    runner('connection', 'add', 'type', 'wifi', 'ifname', '*',
           'con-name', ssid, 'ssid', ssid)
    identity = ('id', ssid)
    # Secret Service retains the Wi-Fi secret, not command-line arguments or
    # plaintext app configuration. Password is delivered via private file.
    runner('connection', 'modify', *identity, 'wifi-sec.key-mgmt', key_mgmt,
           'wifi-sec.psk-flags', '2')
    activate_wifi(identity, password, runner)


def activate_wifi(identity: tuple[str, str], password: str, runner) -> None:
    """Supply an activation secret without modifying the saved profile."""
    if not password:
        runner('connection', 'up', *identity)
        return
    runtime = Path(os.environ.get('XDG_RUNTIME_DIR') or '/nonexistent')
    private_dir = runtime if runtime.is_dir() and runtime.stat().st_uid == os.getuid() else None
    fd, path = tempfile.mkstemp(prefix='wifi-nm-', dir=str(private_dir) if private_dir else None)
    try:
        os.chmod(path, 0o600)
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            f.write('802-11-wireless-security.psk:' + password + '\n')
        runner('connection', 'up', *identity, 'passwd-file', path)
    finally:
        Path(path).unlink(missing_ok=True)
